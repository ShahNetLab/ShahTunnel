#!/usr/bin/env python3
"""Verify that the local Go/helper source exactly matches S1T-START.sh pin."""
import hashlib
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
installer = root / "S1T-START.sh"
text = installer.read_text(encoding="utf-8")
match = re.search(r'^SOURCE_INPUT_SHA256="([0-9a-f]{64})"$', text, re.MULTILINE)
if not match:
    raise SystemExit("could not find a valid SOURCE_INPUT_SHA256 in S1T-START.sh")
files = [root / "go.mod"]
if (root / "go.sum").is_file():
    files.append(root / "go.sum")
for directory in ("S1T-CAPSULE", "scripts"):
    base = root / directory
    if not base.is_dir():
        raise SystemExit("missing source input directory: " + directory)
    for path in base.rglob("*"):
        # Ignore interpreter-generated bytecode so running the tests does not
        # mutate the reviewed source fingerprint.
        if "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo"):
            continue
        if path.is_symlink():
            raise SystemExit("symlink not allowed in source inputs: " + str(path))
        if path.is_file():
            files.append(path)
files.sort(key=lambda path: path.relative_to(root).as_posix())
digest = hashlib.sha256()
for path in files:
    rel = path.relative_to(root).as_posix().encode("utf-8")
    digest.update(rel + b"\0" + hashlib.sha256(path.read_bytes()).digest() + b"\0")
actual = digest.hexdigest()
expected = match.group(1)
if actual != expected:
    raise SystemExit("source fingerprint mismatch: expected %s got %s" % (expected, actual))
print("Source fingerprint verified: " + actual)
